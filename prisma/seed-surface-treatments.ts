async function main() {
  console.log('开始创建表面处理数据...');

  for (const treatment of surfaceTreatments) {
    // 将数组字段转换为JSON字符串
    const treatmentData = {
      ...treatment,
      applications: JSON.stringify(treatment.applications),
      advantages: JSON.stringify(treatment.advantages),
      limitations: JSON.stringify(treatment.limitations),
      processFlow: JSON.stringify(treatment.processFlow),
      parameters: JSON.stringify(treatment.parameters),
      precautions: JSON.stringify(treatment.precautions)
    };

    const result = await prisma.surfaceTreatment.upsert({
      where: { name: treatment.name },
      update: treatmentData,
      create: treatmentData
    });

    console.log(`✅ 创建/更新表面处理: ${result.name}`);
  }

  console.log('表面处理数据创建完成！');
}

main()
  .catch((e) => {
    console.error('错误:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });